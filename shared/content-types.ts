/** A kind's types, in the catalog's order. */
export const typesOf = (kind: ContentKind): ContentType[] => CONTENT_TYPES.filter((t) => t.kind === kind);

export const contentType = (id: string): ContentType | undefined => CONTENT_TYPES.find((t) => t.id === id);

/** Words as they are compared: lower case, without accents, letters and digits only. */
const plain = (s: string) =>
  s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^\p{L}\p{N}&]+/gu, ' ')
    .trim();

/** Words that say which kind is meant ("a SWOT slide"), not which type. */
const KIND_WORDS: [ContentKind, RegExp][] = [
  ['slide', /^slide$/],
  ['deck', /^(slides|deck|presentation|talk)$/],
  ['doc', /^(document|doc|docs|letter)$/],
  ['section', /^(section|chapter|part)$/],
  ['page', /^(page|site|website|app|tool)$/],
  ['block', /^(block)$/],
  ['sheet', /^(spreadsheet|sheet|excel|workbook)$/],
  ['design', /^(design|designs)$/],
];
const SKIP = new Set(['a', 'an', 'the', 'of', 'for', 'with', 'and', 'to', 'my', 'me', 'our', 'make', 'add', 'new', 'one', 'some', 'please', 'in']);

/**
 * The types that match some words, the best first: each word must be found in a type's label, its other words, its id
 * or its blurb (its start counts most). `kind` keeps one kind; without it, a word naming a kind ("slide") favours it.
 * `shown` adds what the page shows of each (its label and blurb in the app's language), for a box that finds by them.
 */
export function findTypes(words: string, o: { kind?: ContentKind; shown?: (t: ContentType) => string } = {}): ContentType[] {
  const tokens = plain(words)
    .split(' ')
    .filter((w) => w && !SKIP.has(w));
  // A word that names a kind counts where it is found ("cover letter") but leaves nothing out ("SWOT slide").
  const kindOf = (w: string) => KIND_WORDS.find(([, re]) => re.test(w))?.[0];
  const kindsNamed = new Set(o.kind ? [] : tokens.map(kindOf).filter((k): k is ContentKind => !!k));
  if (!tokens.length) return o.kind ? typesOf(o.kind) : [];
  // Only words that name a kind ("slides"): every type of it.
  if (tokens.every(kindOf) && !o.kind) return CONTENT_TYPES.filter((t) => kindsNamed.has(t.kind));
  const scored: { t: ContentType; score: number; at: number }[] = [];
  CONTENT_TYPES.forEach((t, at) => {
    if (o.kind && t.kind !== o.kind) return;
    const fields: [string, number][] = [
      [plain(t.label), 4],
      [plain(`${t.also ?? ''} ${t.id.replace(/^[a-z]+\./, '').replace(/-/g, ' ')}`), 3],
      [plain(o.shown?.(t) ?? ''), 3],
      [plain(`${t.blurb} ${CONTENT_GROUPS[t.kind].find((g) => g.id === t.group)?.label ?? ''}`), 1],
    ];
    let score = 0;
    for (const w of tokens) {
      let best = 0;
      for (const [text, weight] of fields) {
        if (!text) continue;
        // At a word's start counts most, a whole word more, inside a word (or in words without spaces) less.
        const got = ` ${text}`.includes(` ${w}`) ? weight + (text.split(' ').includes(w) ? 1 : 0) : text.includes(w) ? weight / 2 : 0;
        best = Math.max(best, got);
      }
      if (!best && !kindOf(w)) return;
      score += best;
    }
    if (plain(t.label) === tokens.join(' ')) score += 4;
    if (kindsNamed.has(t.kind)) score += 3;
    scored.push({ t, score, at });
  });
  return scored.sort((a, b) => b.score - a.score || a.at - b.at).map((x) => x.t);
}
