// Kinds of thing an agent makes on request, each with what it is asked to make: a slide added to a deck open, a new
// deck, a document, a section added to a document open, a page, a part added to a page open, a spreadsheet. People
// pick one in a gallery (the editors' "made with AI" items, and New in the Library), say what it is about if they
// like, and the request is made from its `ask`, their words and where it goes (content-asks.ts); agents asked for one
// by name read the same `ask` with how_to_make (server/pages/content-types.ts). An `ask` says what goes in it, in what
// order, how it looks and where a picture, a drawing or a chart helps; it is English for the agent, never shown as
// the app's words (the i18n extractor leaves it out), while labels, blurbs and hints are shown and translated. Only
// the gallery (and the agents' tool) loads this list: what other pages need is in content-asks.ts, which has no list.

export type ContentKind = 'slide' | 'deck' | 'doc' | 'section' | 'page' | 'block' | 'sheet' | 'design';

export interface ContentType {
  /** "<kind>.<name>": slide.swot. */
  id: string;
  kind: ContentKind;
  /** Its group among its kind's (CONTENT_GROUPS). */
  group: string;
  /** Its name, on its card. */
  label: string;
  /** What it is, in a line. */
  blurb: string;
  /** A Lucide icon's name ("chart-column"). */
  icon: string;
  /**
   * What the agent is asked to make: what goes in it and where, how it looks, and where pictures help. It starts as a
   * noun in lower case ("a SWOT analysis: …"), to follow "Add one slide after slide 3: ".
   */
  ask: string;
  /** What the words it takes might be: the placeholder of "What about? (optional)". */
  hint?: string;
  /** A slide that needs the web format: a quiz, a poll, a part that answers a tap, 3D. */
  web?: true;
  /** More English words it is found by (never shown). */
  also?: string;
}

