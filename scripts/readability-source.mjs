// Makes server/browser/readability/source.ts and readerable-source.ts from Mozilla's Readability.js and
// Readability-readerable.js beside them (Apache-2.0, kept unchanged with their LICENSE.md), so the server's bundle carries
// the library as strings it can run inside a page: the whole of it for a reader copy, and its quick check of whether a page
// has an article for reader view. Run it again when either file is replaced by a newer version:
// node scripts/readability-source.mjs
import fs from 'node:fs';

const dir = new URL('../server/browser/readability/', import.meta.url);
const files = [
  ['Readability.js', 'source.ts', 'READABILITY_SRC'],
  ['Readability-readerable.js', 'readerable-source.ts', 'READERABLE_SRC'],
];
for (const [from, to, name] of files) {
  const src = fs.readFileSync(new URL(from, dir), 'utf8');
  const out = [
    `// Generated by scripts/readability-source.mjs from ${from} beside it: Mozilla Readability, Copyright (c) 2010 Arc90 Inc,`,
    `// Apache License 2.0 (LICENSE.md beside it). Do not edit; replace ${from} and run the script again.`,
    `export const ${name} = ${JSON.stringify(src)};`,
    '',
  ].join('\n');
  fs.writeFileSync(new URL(to, dir), out);
  console.log(`server/browser/readability/${to}: ${src.length} characters of ${from}`);
}
