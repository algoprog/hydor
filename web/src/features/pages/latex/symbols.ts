/** What a click puts in: the symbol's own insert, or its command (a literal \{ kept so in a snippet). */
export const symInsert = (s: Sym) => s[3] ?? s[0].replace(/\\([{}])/g, '\\\\$1');

/** How a symbol is drawn in the panel (\degree is not KaTeX's: drawn as what it puts in). */
export const symDraw = (s: Sym) => (s[0] === '\\degree' ? '^{\\circ}' : s[0]);
