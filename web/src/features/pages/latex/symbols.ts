// The maths symbols the Symbols panel offers, by group (Greek letters, operators, relations, arrows, brackets, accents,
// big operators, more), each as the command that writes it, the words it is found by, and the package it needs
// beyond LaTeX's own (amssymb, amsmath). What a click puts in is the command; one with an argument leaves a place to
// fill in (${}).

/** A symbol: its command (drawn as it is), words to find it by, its package, and what goes in when it differs. */
export type Sym = [tex: string, words: string, pkg?: string, insert?: string];

export interface SymGroup {
  id: string;
  label: string;
  syms: Sym[];
}

