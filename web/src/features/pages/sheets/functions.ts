/** The arguments of a function as written, split (an argument's place in a call is the comma count before the caret). */
export function argsOf(sig: string): { name: string; args: string[] } {
  const m = /^([^(]+)\((.*)\)$/.exec(sig);
  if (!m) return { name: sig, args: [] };
  return { name: m[1], args: m[2] ? m[2].split(/,\s*/) : [] };
}

/** Which argument the caret is in, given how many commas came before it in the call: past the last, the repeating ones ("value2", "range2, criterion2") come round again. */
export function argAt(args: string[], n: number): number {
  const dots = args.indexOf('…');
  if (dots < 0 || n < dots) return Math.min(n, args.length - 1);
  const seconds = args.slice(0, dots).filter((a) => /2\]?$/.test(a)).length;
  const rep = seconds || args.slice(0, dots).filter((a) => /1$/.test(a)).length || 1;
  const first = Math.max(0, dots - rep);
  return first + ((n - first) % rep);
}
